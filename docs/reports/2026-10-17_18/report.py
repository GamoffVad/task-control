story = []
def p(text, style='body'):
    story.append(Paragraph(text, styles[style]))
def page(number, title, subtitle=None):
    if story: story.append(PageBreak())
    p(f'КОНТРОЛЬ ЗАДАЧ  /  17–18 ОКТЯБРЯ 2026  /  {number:02}', 'kicker')
    p(title, 'h')
    if subtitle: p(subtitle)
def sub(text): p(text, 'sub')
def fig(name, caption, height=300):
    path = ASSETS / name
    w, h = ImageReader(str(path)).getSize()
    scale = min(WIDTH/w, height/h)
    story.append(Spacer(1, 6))
    story.append(Image(str(path), width=w*scale, height=h*scale, hAlign='LEFT'))
    story.append(Spacer(1, 6))
    p(caption, 'small')
def table(headers, rows, widths):
    data = [[Paragraph(escape(x), styles['headcell']) for x in headers]]
    data += [[Paragraph(escape(str(x)), styles['cell']) for x in row] for row in rows]
    t = Table(data, colWidths=[WIDTH*x for x in widths], hAlign='LEFT', repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND',(0,0),(-1,0),NAVY),('VALIGN',(0,0),(-1,-1),'TOP'),
        ('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),
        ('TOPPADDING',(0,0),(-1,-1),8),('BOTTOMPADDING',(0,0),(-1,-1),8),
        ('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white, PALE]),
        ('LINEBELOW',(0,0),(-1,-1),.35,colors.HexColor('#D7E0E7')),
    ]))
    story.append(t)
    story.append(Spacer(1, 12))

