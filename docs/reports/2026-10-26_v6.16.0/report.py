from reportlab.lib.utils import ImageReader

ROOT = Path(__file__).resolve().parents[3]
ASSETS = Path(__file__).resolve().parent / 'assets'
OUT = ROOT / 'output/pdf/Task_Control_Report_v6.16.0_2026-10-26.pdf'
OUT.parent.mkdir(parents=True, exist_ok=True)
for name, filename in [('Body', 'segoeui.ttf'), ('Bold', 'segoeuib.ttf')]:
    pdfmetrics.registerFont(TTFont(name, 'C:/Windows/Fonts/' + filename))
pdfmetrics.registerFontFamily('Body', normal='Body', bold='Bold', italic='Body', boldItalic='Bold')

NAVY = colors.HexColor('#193652')
INK = colors.HexColor('#263746')
MUTED = colors.HexColor('#657482')
BLUE = colors.HexColor('#4F7EAC')
PALE = colors.HexColor('#EAF0F5')
PAPER = colors.HexColor('#FAF9F5')
LINE = colors.HexColor('#D5DEE6')
W, H = A4
M = 44
CW = W - 2 * M
BOTTOM = 57
TOTAL = 9
c = canvas.Canvas(str(OUT), pagesize=A4, pageCompression=1)
c.setTitle('Контроль задач - отчёт по версии 6.16.0')
c.setAuthor('Контроль задач / отчёт о выпуске')
c.setSubject('Календарь, календарные показатели, дежурства, иерархия доступа и обновление SQL Server')
y = H - 80
page_no = 0
figure_no = 0
layout = []

def clean(text):
    return str(text).replace('\u2011', '-').replace('\u2013', '-').replace('\u2014', '-')

def p(text, size=10.5, leading=15.5, bold=False, color=INK, after=9, x=M, width=CW):
    global y
    style = ParagraphStyle('text', fontName='Bold' if bold else 'Body', fontSize=size,
                           leading=leading, textColor=color, allowWidows=0, allowOrphans=0)
    obj = Paragraph(clean(text), style)
    _, height = obj.wrap(width, H)
    assert y - height >= BOTTOM, f'Page {page_no}: paragraph overflows at {y-height:.1f}: {text[:70]}'
    obj.drawOn(c, x, y - height)
    y -= height + after
    return height

def sub(text):
    p(text, size=12, leading=16.5, bold=True, color=NAVY, after=6)

def page(title, section='ИЗМЕНЕНИЯ ВЫПУСКА', intro=None):
    global y, page_no
    if page_no:
        finish()
    page_no += 1
    c.setFillColor(PAPER); c.rect(0, 0, W, H, fill=1, stroke=0)
    c.setFillColor(MUTED); c.setFont('Bold', 8)
    c.drawString(M, H - 33, 'КОНТРОЛЬ ЗАДАЧ / 6.16.0')
    c.drawRightString(W - M, H - 33, '26.10.2026')
    c.setStrokeColor(LINE); c.setLineWidth(.6); c.line(M, H - 45, W - M, H - 45)
    y = H - 66
    p(section, size=8, leading=11, bold=True, color=BLUE, after=7)
    p(title, size=25, leading=29, bold=True, color=NAVY, after=13)
    if intro:
        p(intro, color=MUTED)

def finish():
    layout.append({'page': page_no, 'remaining_points': round(y - BOTTOM, 1)})
    c.setStrokeColor(LINE); c.setLineWidth(.5); c.line(M, 39, W - M, 39)
    c.setFillColor(MUTED); c.setFont('Body', 8)
    c.drawString(M, 25, 'Отчёт об изменениях / версия 6.16.0')
    c.drawRightString(W - M, 25, f'{page_no:02} / {TOTAL:02}')
    c.showPage()

def fig(filename, caption, max_h=285):
    global y, figure_no
    path = ASSETS / filename
    iw, ih = ImageReader(str(path)).getSize()
    scale = min(CW / iw, max_h / ih)
    width, height = iw * scale, ih * scale
    assert y - height >= BOTTOM + 30, f'Page {page_no}: image does not fit'
    c.drawImage(str(path), M + (CW - width) / 2, y - height,
                width=width, height=height, mask='auto')
    c.setStrokeColor(LINE); c.setLineWidth(.5)
    c.rect(M + (CW - width) / 2, y - height, width, height, stroke=1, fill=0)
    y -= height + 6
    figure_no += 1
    p(f'<b>Рис. {figure_no}.</b> {caption}', size=8, leading=11, color=MUTED, after=12)

def table(headers, rows, shares, size=9.1, leading=12.6, pad=8):
    global y
    body = ParagraphStyle('cell', fontName='Body', fontSize=size, leading=leading, textColor=INK)
    head = ParagraphStyle('head', parent=body, fontName='Bold', textColor=colors.white)
    values = [[Paragraph(escape(clean(t)), head) for t in headers]]
    values += [[Paragraph(escape(clean(t)), body) for t in row] for row in rows]
    obj = Table(values, colWidths=[CW * share for share in shares], hAlign='LEFT')
    obj.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), NAVY),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, PALE]),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), pad), ('RIGHTPADDING', (0, 0), (-1, -1), pad),
        ('TOPPADDING', (0, 0), (-1, -1), pad), ('BOTTOMPADDING', (0, 0), (-1, -1), pad),
        ('LINEBELOW', (0, 0), (-1, -1), .4, LINE),
    ]))
    _, height = obj.wrap(CW, H)
    assert y - height >= BOTTOM, f'Page {page_no}: table overflows by {BOTTOM-y+height:.1f}'
    obj.drawOn(c, M, y - height)
    y -= height + 13

def metrics(values):
    global y
    gap = 9
    width = (CW - gap * (len(values) - 1)) / len(values)
    for i, (value, label) in enumerate(values):
        x = M + i * (width + gap)
        c.setFillColor(PALE); c.rect(x, y - 75, width, 75, fill=1, stroke=0)
        c.setFillColor(NAVY); c.setFont('Bold', 27); c.drawString(x + 12, y - 32, value)
        c.setFillColor(MUTED); c.setFont('Body', 9); c.drawString(x + 12, y - 55, label)
    y -= 91


def link(label, url):
    p(f'<link href="{url}" color="#245B8B"><u>{label}</u></link>', size=10, leading=14, after=7)


def hierarchy():
    global y
    box_w = (CW - 22) / 3
    top = y
    def box(x, yy, w, h, text, fill=PALE):
        c.setFillColor(fill); c.rect(x, yy-h, w, h, fill=1, stroke=0)
        paragraph = Paragraph(text, ParagraphStyle('node',fontName='Bold',fontSize=9,leading=12,textColor=NAVY,alignment=1))
        paragraph.wrap(w-16,h)
        paragraph.drawOn(c,x+8,yy-h+13)
    box(M+CW*.25,top,CW*.5,42,'Родительский отдел')
    c.setStrokeColor(BLUE); c.setLineWidth(1)
    c.line(M+CW/2,top-42,M+CW/2,top-63)
    c.line(M+box_w/2,top-63,M+CW-box_w/2,top-63)
    for index,label in enumerate(['Руководство отдела','Отделение А','Отделение Б']):
        x=M+index*(box_w+11)
        c.line(x+box_w/2,top-63,x+box_w/2,top-79)
        box(x,top-79,box_w,44,label,colors.HexColor('#DDEAF5') if index==0 else PALE)
    y-=139
    p('Схема: руководители группы «Руководство отдела» представляют родительский отдел и видят задачи обоих отделений. Доступ к соседнему отделу этим правилом не открывается.',size=8.5,leading=12,color=MUTED)


